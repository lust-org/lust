#!/usr/bin/env python3
"""Generate lust_help.h: the LIBRARIES section of `lust --help`.

usage: tools/gen-help.py OUTPUT NAME=doc-shortform.txt...

Every library documents its API as succinctly as possible in
libs/<name>/doc-shortform.txt. This script concatenates them (sorted by
library name, so the result does not depend on the order meson passes
them in) into one C string literal, LUST_HELP_LIBRARIES, which src/lust_main.c
prints behind the options for `lust --help`.

Format of a doc-shortform.txt: blocks separated by blank lines. The first
line of a block is a signature at column 0 (`name(args): result`, or
`name: type` for a non-function value; methods of returned objects are
written `obj:method(args): result`), further lines are an indented
description. Plain text, no tabs; the output indents it below the library
name:

  hash.xxh
    xxh32(str [, seed]): number
      32 bit hash of str ...

The output is a pure function of the inputs (builds are deterministic).
"""

import sys
from pathlib import Path


def fail(msg):
    sys.exit(f"gen-help.py: {msg}")


def read_doc(name, path):
    """The blocks of one doc-shortform.txt, as lists of lines."""
    text = Path(path).read_text(encoding="utf-8")
    if "\t" in text:
        fail(f"{path}: tabs are not allowed, indent with spaces")
    blocks, cur = [], []
    for n, line in enumerate(text.splitlines(), 1):
        line = line.rstrip()
        if line:
            if not cur and line[0] == " ":
                fail(f"{path}:{n}: a block starts with an unindented line")
            cur.append(line)
        elif cur:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)
    if not blocks:
        fail(f"{path}: {name} documents nothing")
    return blocks


def c_literal(line):
    """One line of text as a C string literal (with its newline)."""
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{esc}\\n"'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out, docs = sys.argv[1], {}
    for arg in sys.argv[2:]:
        name, sep, path = arg.partition("=")
        if not sep:
            fail(f"expected NAME=PATH, got {arg!r}")
        docs[name] = read_doc(name, path)

    lines = []
    for name in sorted(docs):
        if lines:
            lines.append("")
        lines.append(f"  {name}")
        for i, block in enumerate(docs[name]):
            if i:
                lines.append("")
            lines += [f"    {line}" for line in block]

    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen-help.py, do not edit. */\n")
        f.write("#ifndef LUST_HELP_H\n#define LUST_HELP_H\n\n")
        f.write("#define LUST_HELP_LIBRARIES \\\n")
        f.write(" \\\n".join("  " + c_literal(line) for line in lines))
        f.write("\n\n#endif\n")


main()
