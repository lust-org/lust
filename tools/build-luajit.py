#!/usr/bin/env python3
"""Build the static LuaJIT runtime (libluajit.a) out of the vendored sources.

LuaJIT's makefile only supports in-tree builds. To keep the vendored
source tree pristine and to make the build directory self-contained, the
`src/` and `dynasm/` trees are mirrored into a work directory below the meson build dir
and built there. Mirroring only copies files that changed, so repeated runs
are incremental and `make` has nothing to do when nothing changed.

This script is invoked by meson (see vendor/meson.build), not by hand.
"""

import argparse
import filecmp
import os
import shutil
import subprocess
import sys
from pathlib import Path


def mirror(src: Path, dst: Path) -> None:
    """Copy `src` to `dst`, but only files whose content differs."""
    for path in src.rglob("*"):
        target = dst / path.relative_to(src)
        if path.is_dir():
            target.mkdir(parents=True, exist_ok=True)
        elif not target.exists() or not filecmp.cmp(path, target, shallow=True):
            target.parent.mkdir(parents=True, exist_ok=True)
            # copy2 keeps the mtime, so make's dependency tracking stays valid.
            shutil.copy2(path, target)


def update_if_changed(built: Path, out: Path) -> None:
    """Only touch `out` when content changed, so ninja doesn't relink."""
    if not out.exists() or not filecmp.cmp(built, out, shallow=False):
        shutil.copyfile(built, out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, type=Path, help="vendored LuaJIT checkout")
    ap.add_argument("--work", required=True, type=Path, help="scratch build directory")
    ap.add_argument("--cc", required=True, help="C compiler command")
    ap.add_argument("--xcflags", default="", help="extra CFLAGS for LuaJIT")
    ap.add_argument("--out-lib", required=True, type=Path)
    ap.add_argument("--out-vmdef", required=True, type=Path)
    ap.add_argument("--out-header", required=True, type=Path)
    ap.add_argument("--out-bin", required=True, type=Path)
    args = ap.parse_args()

    src, work = args.src.resolve(), args.work.resolve()
    if not (src / "src" / "lj_arch.h").exists():
        sys.exit(
            f"error: {src} has no LuaJIT sources (see vendor/vendor.toml)"
        )

    work.mkdir(parents=True, exist_ok=True)
    # `src` is the VM, `dynasm` the assembler its build generates code with.
    for sub in ("src", "dynasm"):
        mirror(src / sub, work / sub)

    # The version string (`LuaJIT 2.1.<relver>`) normally comes from the
    # upstream git history, which the vendored copy does not carry. Use the
    # commit time of the last change to vendor/luajit instead, so the
    # string is stable and changes whenever the vendored copy is updated.
    git = subprocess.run(
        ["git", "-C", str(src), "log", "-1", "--format=%ct", "--", "."],
        capture_output=True,
        text=True,
    )
    if git.returncode == 0 and git.stdout.strip():
        (work / ".relver").write_text(git.stdout.strip() + "\n")

    # `amalg` compiles the VM as one translation unit (faster/smaller).
    # BUILDMODE=static makes libluajit.a only, we link our own main.
    cmd = [
        "make",
        "-C", str(work / "src"),
        f"-j{os.cpu_count() or 1}",
        "amalg",
        "BUILDMODE=static",
        f"CC={args.cc}",
        f"XCFLAGS={args.xcflags}",
    ]
    subprocess.run(cmd, check=True)

    update_if_changed(work / "src" / "libluajit.a", args.out_lib)
    # jit/vmdef.lua is generated by the build and needed by jit.dump & co.
    update_if_changed(work / "src" / "jit" / "vmdef.lua", args.out_vmdef)
    # luajit.h carries the generated version macros, luajit.c includes it.
    update_if_changed(work / "src" / "luajit.h", args.out_header)
    # The interpreter built along with it runs at build time (`luajit -b`
    # turns the Lua part of FFI libraries into bytecode).
    update_if_changed(work / "src" / "luajit", args.out_bin)
    args.out_bin.chmod(0o755)
    return 0


if __name__ == "__main__":
    sys.exit(main())
