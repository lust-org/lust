#!/usr/bin/env python3
"""Embed the source of a library's Lua part (lib_lua) as a C array.

usage: embed-lua-source.py <id> <in.lua> <out.h>

Defines lust_lua_src_<id>[] and lust_lua_src_<id>_SIZE, next to the
LuaJIT bytecode `luajit -b` makes of the same file. The bytecode loads
fastest, but only into a LuaJIT with the bytecode format of the one that
built it; PUC Lua 5.1 and other LuaJIT builds get the source compiled
instead (see include/lust_lua.h). The output depends on the file's
contents only (reproducible builds).
"""

import sys
from pathlib import Path

PER_LINE = 24


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    ident, src, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    data = src.read_bytes()
    lines = [
        ",".join(str(b) for b in data[i:i + PER_LINE])
        for i in range(0, len(data), PER_LINE)
    ]
    out.write_text(
        f"/* The source of {src.name}, generated by tools/embed-lua-source.py */\n"
        f"#define lust_lua_src_{ident}_SIZE {len(data)}\n"
        f"static const unsigned char lust_lua_src_{ident}[] = {{\n"
        + ",\n".join(lines)
        + "\n};\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
